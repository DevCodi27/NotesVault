<#
.SYNOPSIS
    Quick Capture Tool for NotesVault
.DESCRIPTION
    Captures notes from the clipboard or creates a new note from the template.
    If the clipboard contains a #savenote generated by AI, it automatically detects
    the topic and saves it into 00_Inbox or the appropriate stack directory.
.EXAMPLE
    .\quick-capture.ps1
    .\quick-capture.ps1 -Topic "Goroutines" -Stack "Go" -Category "01_Languages"
#>
param (
    [string]$Topic,
    [string]$Stack,
    [ValidateSet("01_Languages", "02_Frameworks", "03_DevOps_Cloud", "04_Data_Storage", "05_Architecture", "00_Inbox")]
    [string]$Category = "00_Inbox",
    [switch]$FromClipboard
)

$VaultRoot = if ($env:NOTES_VAULT) { $env:NOTES_VAULT } else { "D:\Desktop Projects\NotesVault" }
$TemplatePath = Join-Path $VaultRoot "99_Templates\Universal-Tech-Note.md"
$Today = Get-Date -Format "yyyy-MM-dd"

# Check clipboard if flag set or if no parameters provided
$ClipText = ""
try {
    Add-Type -AssemblyName System.Windows.Forms
    $ClipText = [System.Windows.Forms.Clipboard]::GetText()
} catch {
    # Headless fallback
    try {
        $ClipText = Get-Clipboard -Raw -ErrorAction SilentlyContinue
    } catch {}
}

# Auto-detect if clipboard has an AI generated note
if (-not $Topic -and $ClipText -match "topic:\s*[`"']?([^`"'\r\n]+)[`"']?") {
    $DetectedTopic = $Matches[1].Trim()
    Write-Host "[Auto-Detected Topic from Clipboard]: $DetectedTopic" -ForegroundColor Green
    $Topic = $DetectedTopic
}

if (-not $Topic) {
    $Topic = Read-Host "Enter Note Topic (e.g. Concurrency Patterns, Async Await)"
    if (-not $Topic) {
        Write-Warning "Topic cannot be empty. Aborted."
        exit
    }
}

# Clean slug for filename
$Slug = ($Topic -replace '[^\w\s-]', '' -replace '\s+', '-').Trim()
$FileName = "$Slug.md"

# Determine target directory
$TargetDir = Join-Path $VaultRoot $Category
if ($Stack -and $Category -ne "00_Inbox") {
    $TargetDir = Join-Path $TargetDir $Stack
    if (-not (Test-Path $TargetDir)) {
        New-Item -ItemType Directory -Path $TargetDir -Force | Out-Null
    }
}
$DestinationFile = Join-Path $TargetDir $FileName

if (Test-Path $DestinationFile) {
    $Response = Read-Host "File '$FileName' already exists in $TargetDir. Overwrite? (y/n)"
    if ($Response -ne "y") {
        $FileName = "$Slug-" + (Get-Date -Format "HHmmss") + ".md"
        $DestinationFile = Join-Path $TargetDir $FileName
    }
}

# If clipboard contains the markdown note from Gemini/ChatGPT, write it directly
if ($ClipText -and ($ClipText -match "## 1\. Mental Model" -or $ClipText -match "# $Topic" -or $ClipText -match "---")) {
    Set-Content -Path $DestinationFile -Value $ClipText -Encoding UTF8
    Write-Host "`n[SUCCESS] AI note saved from clipboard to:" -ForegroundColor Green
    Write-Host "  $DestinationFile" -ForegroundColor Cyan
} else {
    # Generate from template
    if (Test-Path $TemplatePath) {
        $StackVal = if ($Stack) { $Stack } else { "General" }
        $StackTag = if ($Stack) { $Stack.ToLower() } else { "tech" }
        $CatTag = ($Category -replace "^\d+_", "").ToLower()
        $CodeLang = if ($Stack) { $Stack.ToLower() } else { "text" }

        $Content = Get-Content -Path $TemplatePath -Raw -Encoding UTF8
        $Content = $Content -replace "{{TOPIC}}", $Topic
        $Content = $Content -replace "{{STACK}}", $StackVal
        $Content = $Content -replace "{{CATEGORY}}", $Category
        $Content = $Content -replace "{{STACK_TAG}}", $StackTag
        $Content = $Content -replace "{{CATEGORY_TAG}}", $CatTag
        $Content = $Content -replace "{{DATE}}", $Today
        $Content = $Content -replace "{{SOURCE_URL_OR_NAME}}", "Manual Note"
        $Content = $Content -replace "{{CODE_LANG}}", $CodeLang

        Set-Content -Path $DestinationFile -Value $Content -Encoding UTF8
        Write-Host "`n[SUCCESS] New note scaffolded at:" -ForegroundColor Green
        Write-Host "  $DestinationFile" -ForegroundColor Cyan
    } else {
        Set-Content -Path $DestinationFile -Value "# $Topic`nDate: $Today`n" -Encoding UTF8
        Write-Host "`n[SUCCESS] Note created at: $DestinationFile" -ForegroundColor Green
    }
}

Write-Host "Done! You can open it in VS Code or Obsidian.`n" -ForegroundColor Yellow
